#!/usr/bin/env python3
"""Generate src/emu/tables.rs from the original Python RetroImpact app.

usage: python3 tools/gen_tables.py /path/to/retroimpact   (the folder that contains the `retroimpact` package)

The tables are things that are awkward to recompute in Rust without Python's unicode database / PIL:
code page tables, the draft font (incl. composed accents), box-drawing stroke arms.
"""
import sys

sys.path.insert(0, sys.argv[1])
from retroimpact import charsets, glyphs as G  # noqa: E402

out = ["// @generated by tools/gen_tables.py from the Python RetroImpact app. Do not edit.", ""]


def chars_array(name, chars):
    items = ", ".join("0x%04X" % ord(c) for c in chars)
    out.append(f"pub static {name}: [u32; {len(chars)}] = [{items}];")


# ---- code pages: bytes 0x80..0xFF
for cp, key in (("CP437", "cp437"), ("CP850", "cp850"), ("LATIN1", "latin1"), ("MAC_ROMAN", "mac_roman")):
    chars_array(cp + "_HIGH", [charsets.decode(b, key, 0) or "?" for b in range(0x80, 0x100)])
chars_array("CP437_LOW", charsets.CP437_LOW)
out.append("")

# ---- the draft font, for every character any emulator can ask for
want = set(chr(c) for c in range(0x20, 0x7F)) | {"?"}
for key in ("cp437", "cp850", "latin1", "mac_roman"):
    for b in range(0x80, 0x100):
        want.add(charsets.decode(b, key, 0) or "?")
for v in charsets.NATIONAL.values():
    want |= set(v)
want |= set(charsets.CP437_LOW)
for lower in (False, True):
    for b in range(256):
        c = charsets.petscii_char(b, lower)
        if c:
            want.add(c)
rows = []
for ch in sorted(want, key=ord):
    g = G.draft_glyph(ch)
    bits = g.bits
    assert bits.shape[0] == 9 and bits.shape[1] <= 8, (ch, bits.shape)
    masks = []
    for r in range(9):
        m = 0
        for c in range(bits.shape[1]):
            if bits[r, c]:
                m |= 1 << c
        masks.append(m)
    rows.append((ord(ch), bool(g.full_cell), bits.shape[1], masks))
out.append("/// (char, full_cell, columns, nine row masks: bit c = column c)")
out.append(f"pub static DRAFT: [(u32, bool, u8, [u8; 9]); {len(rows)}] = [")
for o, full, cols, masks in rows:
    out.append("    (0x%04X, %s, %d, [%s])," % (o, "true" if full else "false", cols, ", ".join(str(m) for m in masks)))
out.append("];")
out.append("")

# ---- box drawing arms
arms = []
for o in range(0x2500, 0x2580):
    a = G.box_arms(chr(o))
    if a is not None:
        arms.append((o, a))
out.append("/// (char, left, right, up, down) stroke styles: 0 none, 1 single, 2 double")
out.append(f"pub static BOX_ARMS: [(u32, u8, u8, u8, u8); {len(arms)}] = [")
for o, (l, r, u, d) in arms:
    out.append(f"    (0x{o:04X}, {l}, {r}, {u}, {d}),")
out.append("];")
out.append("")

open("src/emu/tables.rs", "w").write("\n".join(out) + "\n")
print("draft glyphs:", len(rows), "box chars:", len(arms))
